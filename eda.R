winsor <- function(x, lo = 0.01, hi = 0.99) {
  q <- quantile(x, c(lo, hi), na.rm = TRUE, names = FALSE)
  pmin(pmax(x, q[1]), q[2])
}
bank_w <- bank |> mutate(across(all_of(continuous_cols), winsor))

# determine most important features - which ones have the most seperation between failure/success
# Univariate AUC: probability a random failing row has a higher value than a random surviving row. 0.5 = no signal. AUC is unaffected by downsampling.
auc_one <- function(x, y) {
  keep <- !is.na(x)
  x <- x[keep]; y <- y[keep]
  n1 <- sum(y == 1); n0 <- sum(y == 0)
  r <- rank(x)
  (sum(r[y == 1]) - n1 * (n1 + 1) / 2) / (n1 * n0)
}

auc_tbl <- map_dfr(feature_cols, \(f) tibble(
  feature = f,
  auc     = auc_one(bank[[f]], bank$failed_within_4q)
)) |>
  mutate(direction  = if_else(auc >= 0.5, "Higher = riskier", "Lower = riskier"),
         separation = abs(auc - 0.5) * 2) |>     # 0 = none, 1 = perfect
  arrange(desc(separation))

